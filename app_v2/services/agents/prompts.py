def normalize_dimension_name(raw: str) -> str:
    """把模型输出的维度名归一化到标准维度名。

    步骤：
    1. 去掉首尾空白与全角空格；
    2. 若已经是标准维度名 → 原样返回；
    3. 若命中别名表 → 换算成标准维度名；
    4. 否则（全新维度）→ 原样返回，交给上层标"待确认"。
    """
    name = (raw or "").strip().replace("　", " ")
    if not name:
        return ""
    if name in DIMENSION_NAMES:
        return name
    return DIMENSION_ALIASES.get(name, name)


