"""自定义异常类型。

异常可以理解成"程序出问题时抛出的求助信号"。这里定义了自己的一套异常，
让代码能区分不同错误类型：找不到数据、外部服务出错等。
上层根据异常类型，就能给用户返回更准确的提示。
"""


class AppError(Exception):
    """所有自定义异常的父类，捕获它可以一次性接住所有自定义错误。"""


class NotFoundError(AppError):
    """表示"要找的数据不存在"（例如要打开的笔记已被删除）。"""


class ProviderError(AppError):
    """表示"外部服务出错"（例如调用大模型或抓取工具失败）。"""
